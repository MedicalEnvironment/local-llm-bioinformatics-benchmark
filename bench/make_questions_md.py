"""Write docs/QUESTIONS.md: every benchmark item with its answer key and source, generated from tasks.py and truth.json."""
import json, re
from pathlib import Path
import tasks

B = Path(__file__).parent
T = json.load(open(B / "data/truth.json"))
gene = json.load(open(B / "data/raw/gene_summaries.json"))["result"]
loc = {gene[u]["name"]: gene[u]["maplocation"] for u in gene["uids"]}
cell = lambda s: str(s).replace("|", "\\|").replace("\n", " ")

def key(tid):
    t = T[tid]
    if tid == "gc_content": return "; ".join(f"{g} {v}" for g, v in t.items()) + " (each within ±0.011)"
    if tid == "translate": return "; ".join(f"{g} {v} aa" for g, v in t.items()) + " (exact)"
    if tid == "longest_orf": return f"{t['start']} {t['end']} {t['strand']} {t['length']} (exact)"
    if tid == "gff_summary": return "; ".join(f"{k} {v}" for k, v in sorted(t['counts'].items())) + f"; total_cds_bp {t['total_cds_bp']} (exact)"
    if tid == "vcf_filter": return f"kept={t['kept']} snv={t['snv']} indel={t['indel']} titv={t['titv']} (counts exact, titv ±0.0011)"
    if tid == "fastq_qc": return f"reads={t['reads']} pass_q20={t['pass_q20']} mean_q={t['overall_mean_q']} (counts exact, mean ±0.011)"
    if tid == "kmer": return f"one of {', '.join(t['ties'])} with count {t['count']}"

# Accepted answers in words; the exact regular expression from tasks.py is shown beside it.
ACCEPT = {"sam_mapq": "-q or --min-MQ", "sam_reqflag": "-f or --require-flags", "sam_threads": "-@ or --threads",
          "sam_byname": "-n", "markdup_rm": "-r or --remove", "depth_all": "-a or -aa", "bcf_snps": "-v snps or --types snps",
          "bcf_norm": "norm", "seqkit_rmdup": "-s or --by-seq", "seqkit_stats": "stats"}

L = ["# The 53 benchmark items and how each was scored", "",
     "Generated by `bench/make_questions_md.py` from `bench/tasks.py` and `bench/data/truth.json`; do not edit by hand.", "",
     "Every model got exactly these prompts. Scripts were also told: *" + tasks.FMT + "*", "",
     "## Scripting (7): the generated script is run, and its printed output must match the key", "",
     "| ID | Task given to the model | Input file | Correct output (computed by `make_data.py`) |", "| --- | --- | --- | --- |"]
for t in tasks.SCRIPT_TASKS:
    L.append(f"| {t['id']} | {cell(t['prompt'])} | {', '.join(t['files'])} | {cell(key(t['id']))} |")
L += ["", "## Reasoning (10): the final `ANSWER:` number must be within 1% of the key", "",
      "Each question ended with: *" + cell(tasks.REASON_SUFFIX.strip()) + "*", "",
      "| ID | Question | Correct answer |", "| --- | --- | --- |"]
for tid, q, want in tasks.REASON_TASKS:
    L.append(f"| {tid} | {cell(q)} | {want} |")
L += ["", "## Retrieval (18, each asked twice): the final `ANSWER:` line must contain an accepted answer", "",
      "Asked once from memory (closed-book) and once with the five best-matching documentation excerpts pasted above the question (RAG). Each question ended with: *" + cell(tasks.RETR_SUFFIX.strip()) + "*", "",
      "| ID | Question | Accepted answer | Source of the key | Scoring pattern |", "| --- | --- | --- | --- | --- |"]
for tid, q, pat in tasks.RETR_TASKS:
    if tid.startswith("loc_"):
        g = tid[4:]; acc, src = f"`{loc[g]}`", f"NCBI Gene `maplocation` for {g}"
    else:
        acc, src = ACCEPT[tid], "Tool manual in `bench/data/docs/`"
    L.append(f"| {tid} | {cell(q)} | {acc} | {src} | `` {cell(pat)} `` |")
L += ["", "The exact scoring code is `score_script`, `score_reason` and `score_retr` in `bench/tasks.py`."]
(B.parent / "docs/QUESTIONS.md").write_text("\n".join(L) + "\n")
