"""Write docs/RESULTS_BY_ITEM.md (every item x every run) and docs/EXAMPLES.md (real answers, quoted verbatim)
from the result files in bench/results/. Rerun after adding results: python bench/make_results_md.py"""
import json
from pathlib import Path
import tasks

B = Path(__file__).parent; R = B / "results"; D = B.parent / "docs"
RUNS = [("hpc-qwen3.5-122b-a10b", "122B HPC"), ("t4-qwen3.5-35b-a3b", "35B T4"), ("t4-gpt-oss-20b", "gpt-oss-20b T4"),
        ("hpc-qwen3.5-9b", "9B HPC"), ("t4-qwen3.5-9b", "9B T4"), ("laptop-qwen3.5-9b", "9B laptop"),
        ("t4-gemma4-e4b", "Gemma-E4B T4"), ("laptop-gemma4-e4b", "Gemma-E4B laptop")]
res = {r: json.load(open(R / f"{r}.json"))["items"] for r, _ in RUNS}
order = ([f"script:{t['id']}" for t in tasks.SCRIPT_TASKS] + [f"reason:{t[0]}" for t in tasks.REASON_TASKS]
         + [f"closed:{t[0]}" for t in tasks.RETR_TASKS] + [f"rag:{t[0]}" for t in tasks.RETR_TASKS])
SEC = {"script": "Scripting", "reason": "Calculations", "closed": "Facts from memory (closed-book)", "rag": "Facts with documentation (RAG)"}

L = ["# Results for every item", "",
     "Each cell is one answer: **✓** correct, **✗** wrong, **✗ cut off** = the answer hit the output-length limit before its final line.",
     "Generated by `bench/make_results_md.py` from `bench/results/*.json`. Questions and correct answers: [QUESTIONS.md](QUESTIONS.md).", "",
     "Run columns: model and machine (HPC = RTU HPC L40S, T4 = Azure Tesla T4, laptop = RTX 4060 8 GB).", ""]
hdr = "| Item | " + " | ".join(n for _, n in RUNS) + " | Correct in |"
sep = "| --- | " + " | ".join("---" for _ in RUNS) + " | --- |"
cur = None
for k in order:
    s = k.split(":")[0]
    if s != cur:
        if cur:
            L.append("| **Section total** | " + " | ".join(f"**{sum(res[r][x]['ok'] for x in order if x.startswith(cur + ':'))}**" for r, _ in RUNS) + " | |")
        cur = s; L += ["", f"## {SEC[s]}", "", hdr, sep]
    cells = []
    for r, _ in RUNS:
        v = res[r][k]
        cells.append("✓" if v["ok"] else ("✗ cut off" if v.get("finish") == "length" else "✗"))
    L.append(f"| {k.split(':')[1]} | " + " | ".join(cells) + f" | {sum(res[r][k]['ok'] for r, _ in RUNS)}/{len(RUNS)} |")
L.append("| **Section total** | " + " | ".join(f"**{sum(res[r][x]['ok'] for x in order if x.startswith(cur + ':'))}**" for r, _ in RUNS) + " | |")
L += ["", "## Overall", "", "| | " + " | ".join(n for _, n in RUNS) + " |", "| --- | " + " | ".join("---" for _ in RUNS) + " |",
      "| **Total /53** | " + " | ".join(f"**{sum(v['ok'] for v in res[r].values())}**" for r, _ in RUNS) + " |"]
(D / "RESULTS_BY_ITEM.md").write_text("\n".join(L) + "\n")

# ---- worked examples, quoted verbatim ----
T = json.load(open(B / "data/truth.json"))
def block(s, lang="", n=40):
    lines = (s or "").rstrip().splitlines()
    more = len(lines) - n
    return f"```{lang}\n" + "\n".join(lines[:n]) + (f"\n# ... {more} more lines" if more > 0 else "") + "\n```"
it = lambda r, k: res[r][k]
E = ["# Worked examples: what the models actually wrote", "",
     "Real answers copied verbatim from `bench/results/` by `bench/make_results_md.py` (long scripts are shortened). "
     "They show the three outcomes that matter in practice: correct, silently wrong, and crashed.", ""]

v = it("hpc-qwen3.5-122b-a10b", "script:vcf_filter")
E += ["## 1. Correct: VCF filtering (Qwen3.5-122B-A10B, HPC)", "",
      "Task: keep PASS records with QUAL ≥ 30 and DP ≥ 10, count SNVs and indels, compute Ts/Tv. The input `calls.vcf` "
      "deliberately has only 8 columns.", "", block(v["code"], "python"), "", "Output when run on `calls.vcf`:", "", block(v["stdout"]), "",
      f"Correct answer: `kept={T['vcf_filter']['kept']} snv={T['vcf_filter']['snv']} indel={T['vcf_filter']['indel']} titv={T['vcf_filter']['titv']}` → **pass**.", ""]

v = it("laptop-qwen3.5-9b", "script:vcf_filter")
E += ["## 2. Silently wrong: the same task (Qwen3.5-9B, laptop)", "",
      "This script ran without any error, so a user would likely trust it. It skips every line with fewer than 9 columns "
      "(this VCF validly has 8, as it has no sample columns) and also reads QUAL from column 8 (INFO) instead of column 6, so nothing is kept.", "", block(v["code"], "python", 30), "", "Output:", "", block(v["stdout"]), "",
      f"Correct answer: `kept={T['vcf_filter']['kept']} ...` → **fail**. Nothing in the output signals a problem; only checking against a known answer catches it.", ""]

v = it("laptop-qwen3.5-9b", "script:gc_content")
E += ["## 3. Silently wrong in a subtler way: GC content (Qwen3.5-9B, laptop)", "",
      "Every GC percentage is correct, but an off-by-one slice drops the first letter of each gene name.", "", "Output (first lines):", "",
      block(v["stdout"], "", 6), "", "Expected: `TP53 56.85`, `BRCA1 41.22`, ... → **fail**.", ""]

v = it("hpc-qwen3.5-9b", "script:vcf_filter")
E += ["## 4. Crashed: an invented library function (Qwen3.5-9B, HPC)", "",
      "The model called `pandas.read_vcf`, which does not exist. A crash is the easy failure: it is obvious.", "",
      "Error output:", "", block(v["stderr"], "", 8), ""]

c, g = it("laptop-gemma4-e4b", "closed:seqkit_rmdup"), it("laptop-gemma4-e4b", "rag:seqkit_rmdup")
lastline = lambda s: [l for l in s.strip().splitlines() if l.strip()][-1]
E += ["## 5. Documentation fixes recall: the same question with and without RAG (Gemma-4-E4B, laptop)", "",
      "Question: *In `seqkit rmdup`, which option removes duplicates by sequence content rather than by ID?* Correct: `-s` / `--by-seq`.", "",
      f"- From memory (closed-book): `{lastline(c['content'])}` → **{'pass' if c['ok'] else 'fail'}**",
      f"- With the seqkit manual excerpt pasted in (RAG): `{lastline(g['content'])}` → **{'pass' if g['ok'] else 'fail'}**", ""]

v = it("t4-gpt-oss-20b", "closed:loc_CFTR")
E += ["## 6. A scoring artefact: right answer, wrong format (gpt-oss-20b, Azure)", "",
      "The scorer only reads a final line that starts with exactly `ANSWER:`. This answer is correct (CFTR is at 7q31.2) "
      "but wrote `Answer:`, so it was scored as wrong. It is the only such case found when every failure was checked by hand.", "",
      block(v["content"].strip()[-300:]), ""]
(D / "EXAMPLES.md").write_text("\n".join(E) + "\n")
print("ok")
